export type IconName = keyof typeof ICONS;

/** Icons that get a fixed accent color (see `.icon-*` in styles.css), like the emoji they replace. */
const TONES: Partial<Record<IconName, string>> = {
  flame: 'flame',
  star: 'gold',
  crown: 'gold',
  trophy: 'gold',
  medal: 'gold',
  award: 'gold',
  heart: 'heart',
  'heart-crack': 'heart',
  gem: 'gem',
  zap: 'gold',
  snowflake: 'gem',
};

interface Props extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  /** Size in px; defaults to 1em so the icon scales with the surrounding text. */
  size?: number | string;
  /** Fill the shape with its accent color (hearts, gems, stars…) instead of an outline only. */
  filled?: boolean;
  /** Spoken label; without it the icon is decorative and hidden from screen readers. */
  label?: string;
}

export function Icon({ name, size = '1em', filled, label, className, ...rest }: Props) {
  const tone = TONES[name];
  const classes = ['icon', tone && `icon-${tone}`, filled && 'icon-filled', className].filter(Boolean).join(' ');
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={classes}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
    >
      {ICONS[name].map(([Tag, attrs], i) => (
        <Tag key={i} {...attrs} />
      ))}
    </svg>
  );
}

/** True for a name this component can draw (data that may still hold an old emoji). */
export function isIconName(value: string): value is IconName {
  return Object.hasOwn(ICONS, value);
}
